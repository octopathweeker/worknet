import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import solc from 'solc';

const root = fileURLToPath(new URL('../', import.meta.url));
const sources = {};
async function collect(dir) {
  for (const name of (await readdir(path.join(root, dir))).sort()) {
    const rel = `${dir}/${name}`;
    if (name.endsWith('.sol')) sources[rel] = { content: await readFile(path.join(root, rel), 'utf8') };
    else if (!name.includes('.')) await collect(rel);
  }
}
await collect('contracts/src/interfaces');
await collect('contracts/src/libraries');
sources['contracts/test/ProtocolHarness.sol'] = { content: await readFile(path.join(root, 'contracts/test/ProtocolHarness.sol'), 'utf8') };
const output = JSON.parse(solc.compile(JSON.stringify({
  language: 'Solidity', sources,
  settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: 'shanghai',
    outputSelection: { '*': { '*': ['abi', 'evm.deployedBytecode.object'] } } }
})));
for (const diagnostic of output.errors ?? []) {
  if (diagnostic.severity === 'error') throw new Error(diagnostic.formattedMessage);
  process.stderr.write(diagnostic.formattedMessage);
}
const manager = output.contracts['contracts/src/interfaces/ITaskManager.sol'].ITaskManager.abi;
const vault = output.contracts['contracts/src/interfaces/IRequesterVault.sol'].IRequesterVault.abi;
const harness = output.contracts['contracts/test/ProtocolHarness.sol'].ProtocolHarness;
const generated = `// Generated by scripts/generate-contracts.mjs. Do not edit.\n` +
  `export const taskManagerAbi = ${JSON.stringify(manager, null, 2)} as const;\n` +
  `export const requesterVaultAbi = ${JSON.stringify(vault, null, 2)} as const;\n`;
const files = {
  'packages/contracts/src/generated.ts': generated,
  'packages/contracts/abi/ITaskManager.json': JSON.stringify(manager, null, 2) + '\n',
  'packages/contracts/abi/IRequesterVault.json': JSON.stringify(vault, null, 2) + '\n',
  'tests/fixtures/protocol-harness.json': JSON.stringify({
    compiler: solc.version(), evmVersion: 'shanghai', abi: harness.abi,
    deployedBytecode: '0x' + harness.evm.deployedBytecode.object,
  }, null, 2) + '\n',
};
for (const [rel, content] of Object.entries(files)) {
  if (process.argv.includes('--check')) {
    if (await readFile(path.join(root, rel), 'utf8') !== content) throw new Error(`Generated artifact drift: ${rel}`);
  } else {
    await mkdir(path.dirname(path.join(root, rel)), { recursive: true });
    await writeFile(path.join(root, rel), content);
  }
}
console.log(`Solidity interfaces + pure harness: ${solc.version()} (${process.argv.includes('--check') ? 'checked' : 'generated'})`);
